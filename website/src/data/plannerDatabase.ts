export function matchApiPackages(
  destName: string,
  stops: RouteStop[] = [],
  apiPackages?: any[]
): MatchedPackage[] {
  if (!Array.isArray(apiPackages) || apiPackages.length === 0) {
    return [];
  }

  const queryTerms = [
    destName.toLowerCase(),
    ...stops.map((s) => s.name.toLowerCase()),
  ];

  // Find packages matching the destination or any stop location
  const directMatches = apiPackages.filter((pkg: any) => {
    const title = (pkg.title || pkg.packageName || "").toLowerCase();
    const loc = (pkg.location || pkg.destination || "").toLowerCase();
    const desc = (pkg.description || pkg.packageDescription || "").toLowerCase();

    return queryTerms.some(
      (term) =>
        term.length > 2 &&
        (loc.includes(term) || title.includes(term) || desc.includes(term))
    );
  });

  const selected = directMatches.length > 0 ? directMatches : apiPackages.slice(0, 3);

  return selected.slice(0, 4).map((pkg: any) => {
    const rawPrice = Number(pkg.price || pkg.discountPrice || 14999);
    const origPrice = pkg.originalPrice ? Number(pkg.originalPrice) : undefined;
    const discount =
      origPrice && rawPrice < origPrice
        ? Math.round(((origPrice - rawPrice) / origPrice) * 100)
        : undefined;

    const firstImage =
      Array.isArray(pkg.images) && pkg.images.length > 0
        ? pkg.images[0]
        : (pkg.image || pkg.coverImage || "/favicon.png");

    return {
      id: pkg._id || pkg.id || pkg.customId || `pkg-${Math.random()}`,
      title: pkg.title || pkg.packageName || `${destName} Tour Package`,
      duration: pkg.duration || "4 Days / 3 Nights",
      price: rawPrice,
      originalPrice: origPrice,
      discountPercent: discount,
      image: getImageUrl(firstImage),
      rating: Number(pkg.rating || pkg.averageRating || 4.8),
      reviewsCount: Number(pkg.reviewsCount || 24),
      location: pkg.location || pkg.destination || destName,
      badge: pkg.badge || (pkg.isFeatured ? "Best Seller" : "Verified Partner"),
      highlights:
        Array.isArray(pkg.inclusions) && pkg.inclusions.length > 0
          ? pkg.inclusions
          : ["Private AC Transport", "Selected Resort Stay", "Breakfast Included"],
      inclusions:
        Array.isArray(pkg.inclusions) && pkg.inclusions.length > 0
          ? pkg.inclusions
          : ["Resort Accommodation", "Daily Breakfast", "Sightseeing Cab", "All Tolls & Permits"],
    };
  });
}

